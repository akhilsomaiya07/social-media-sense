import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const box={module:{exports:{}},Date};vm.createContext(box);
vm.runInContext(await readFile('public/sleep-context.js','utf8'),box);
vm.runInContext(await readFile('public/sleep-patterns.js','utf8'),box);
const {sleepDiaryAnalyze:analyze,sleepDiaryValid:valid,sleepDateOrdinal:ordinal,sleepClockVariation:variation}=box.module.exports;
const today='2026-10-24',start=ordinal(today)-13;
const date=n=>new Date(n*86400000).toISOString().slice(0,10);
const rows=Array.from({length:14},(_,i)=>({sleepDate:date(start+i),sleepMinutes:480,rested:'Rested',fellAsleep:'23:00',wokeUp:'07:00',interrupted:'No',followed:i%2?'No':'Yes',note:''}));
assert(rows.every(valid));
assert.equal(analyze(rows,30,today).kind,'celebrate');
assert.equal(analyze(rows,16,today).kind,'celebrate');
assert.equal(analyze(rows,70,today).kind,'celebrate');
assert.equal(analyze(rows.slice(1),30,today).kind,'insufficient');
assert.equal(analyze(rows.map((r,i)=>i%2?{...r,sleepMinutes:300}:r),30,today).kind,'advice');
assert.equal(analyze(rows.map(r=>({...r,followed:'Yes',sleepMinutes:300})),30,today).kind,'advice');
assert.equal(analyze(rows.map((r,i)=>i%2?{...r,fellAsleep:'02:00'}:r),30,today).kind,'advice');
assert.equal(analyze(rows.map((r,i)=>i===5?{...r,rested:'Not very rested'}:r),30,today).kind,'advice');
assert.equal(analyze(rows.map((r,i)=>i===5?{...r,interrupted:'Yes'}:r),30,today).kind,'advice');
assert.equal(analyze(rows.map(r=>({...r,fellAsleep:''})),30,today).kind,'insufficient');
assert.equal(analyze(rows,null,today).kind,'insufficient');
assert.equal(analyze(rows,30,'2026-11-01').kind,'insufficient');
assert.equal(analyze([...rows,rows[0]],30,today).kind,'insufficient');
assert.equal(analyze(rows.map(r=>({...r,followed:'No'})),30,today).kind,'celebrate');
assert.equal(variation([1430,10,0]),20);
assert.equal(ordinal('2026-02-30'),null);
assert.equal(ordinal('2026-02-28')+1,ordinal('2026-03-01'));
assert(!valid({...rows[0],sleepMinutes:1441}));
assert(!valid({...rows[0],fellAsleep:'25:12'}));
console.log('PASS multiweek sleep analysis, date gaps, age, short and uneven sleep, missing data, interrupted/unrested nights, midnight and independent adherence');
